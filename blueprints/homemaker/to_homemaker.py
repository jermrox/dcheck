"""Export traced AR Homes blueprint models as HOMEMAKER projects (https://github.com/bayllama/homemaker).

Usage: python3 -I to_homemaker.py <models.json> <fp_dir> <homemaker_projects_dir> [base ...]
  models.json   bundled models (blueprints/model/bundle_models.py + apply_reviews.py)
  fp_dir        downloaded blueprint images, named <base>.<ext>
  base ...      only these sheets (default: every model)

Per sheet it writes projects/ar-<base>/:
  project.json   HOMEMAKER manifest: walls (centre lines in metres), camera, scene, the openings room module
  walls.json     the same wall data (HOMEMAKER keeps both)
  floorplan.png  the blueprint, so the floor-plan tool shows walls over the drawing at the right scale
  rooms/openings.js  door headers, window sills/headers and glass at their real heights
  CLAUDE.md      what is traced, how the scale was set, what still needs fixing (read by HOMEMAKER's agent)
HOMEMAKER maps image pixels to metres as px / pixelsPerMeter, so traced pixel coordinates carry over unchanged.
"""
import datetime, glob, json, math, os, sys

FT = 0.3048
CEIL = 2.74                     # 9 ft
DOOR_TOP, SILL, WIN_TOP = 2.05, 0.9, 2.1
GRADE = {"reviewed": "REVIEWED (an AI reviewer read printed room sizes off the sheet; they agree)",
         "mixed": "REVIEWED, MIXED (levels on this sheet are drawn at different scales; first floor scale used)",
         "verified": "VERIFIED (3+ printed dimensions agree)", "rooms": "GOOD (several printed dimensions agree)",
         "room": "FAIR (one printed room size)", "area": "ESTIMATED (published sq ft vs traced outline)",
         "conflict": "NEEDS CHECKING (printed dimensions and published sq ft disagree)", "default": "UNMEASURED"}

def rect_line(x, y, w, h, ppm):
    """Axis-aligned wall rectangle in px -> centre line + thickness in metres."""
    if w >= h: return dict(x1=x / ppm, z1=(y + h / 2) / ppm, x2=(x + w) / ppm, z2=(y + h / 2) / ppm, t=h / ppm)
    return dict(x1=(x + w / 2) / ppm, z1=y / ppm, x2=(x + w / 2) / ppm, z2=(y + h) / ppm, t=w / ppm)

def poly_line(pts, ppm):
    """Angled wall / column polygon -> its minimum-area rectangle as one centre line."""
    import cv2, numpy as np
    (cx, cy), (a, b), ang = cv2.minAreaRect(np.array(pts, np.float32).reshape(-1, 2))
    if a < b: a, b, ang = b, a, ang + 90
    r = math.radians(ang); dx, dy = math.cos(r) * a / 2, math.sin(r) * a / 2
    return dict(x1=(cx - dx) / ppm, z1=(cy - dy) / ppm, x2=(cx + dx) / ppm, z2=(cy + dy) / ppm, t=max(b, 2) / ppm)

def openings_module(openings, ppm):
    rows = []
    for x, y, w, h, k in openings:
        L = rect_line(x, y, w, h, ppm)
        rows.append([round(v, 3) for v in (L["x1"], L["z1"], L["x2"], L["z2"], L["t"])] + [k])
    return f"""// Generated by blueprints/homemaker/to_homemaker.py from the traced AR Homes blueprint.
// Each row: x1, z1, x2, z2 (wall centre line, metres), thickness, kind (0 window, 1 door, 2 cased opening).
// Doors/openings get a header above {DOOR_TOP} m; windows get a sill to {SILL} m, a header from {WIN_TOP} m and glass.
import * as THREE from 'three';
import {{ addWall }} from '../../../js/helpers.js';
import {{ wallMat }} from '../../../js/materials.js';

const OPENINGS = {json.dumps(rows, separators=(',', ':'))};
const glassMat = new THREE.MeshStandardMaterial({{ color: 0x9cc3dd, roughness: 0.05, metalness: 0.1, transparent: true, opacity: 0.35 }});

export function buildOpenings(scene, projectConfig) {{
  const H = projectConfig.walls?.ceilingHeight || {CEIL};
  for (const [x1, z1, x2, z2, t, kind] of OPENINGS) {{
    const len = Math.hypot(x2 - x1, z2 - z1); if (len < 0.05) continue;
    const cx = (x1 + x2) / 2, cz = (z1 + z2) / 2, ang = Math.atan2(-(z2 - z1), x2 - x1);
    const seg = (y0, y1, mat, th) => addWall(scene, mat, cx, (y0 + y1) / 2, cz, len, y1 - y0, 0, ang, th);
    if (kind === 0) {{ seg(0, {SILL}, wallMat, t); seg({WIN_TOP}, H, wallMat, t); seg({SILL}, {WIN_TOP}, glassMat, Math.min(t, 0.03)); }}
    else seg({DOOR_TOP}, H, wallMat, t);
  }}
}}
"""

def export(base, m, fp_dir, out_root):
    imgs = glob.glob(os.path.join(fp_dir, base + ".*"))
    if not imgs: return None
    ppf = 1 / m["s"]; ppm = ppf / FT
    lines = [rect_line(*r, ppm) for r in m["w"]] + [poly_line(p, ppm) for p in m.get("p", []) if len(p) >= 6]
    lines = [dict(x1=round(L["x1"], 4), z1=round(L["z1"], 4), x2=round(L["x2"], 4), z2=round(L["z2"], 4),
                  height=CEIL, thickness=round(max(0.08, min(L["t"], 0.6)), 3)) for L in lines
             if math.hypot(L["x2"] - L["x1"], L["z2"] - L["z1"]) >= 0.15]
    walls = {"scale": {"pixelsPerMeter": ppm}, "ceilingHeight": CEIL, "wallThickness": 0.15, "lines": lines}
    xs = [v for L in lines for v in (L["x1"], L["x2"])]; zs = [v for L in lines for v in (L["z1"], L["z2"])]
    import hashlib
    slug = "ar-" + (base if len(base) <= 60 else base[:51] + "-" + hashlib.sha1(base.encode()).hexdigest()[:8])
    d = os.path.join(out_root, slug); os.makedirs(os.path.join(d, "rooms"), exist_ok=True)
    now = datetime.datetime.now(datetime.timezone.utc).isoformat().replace("+00:00", "Z")
    project = {
        "name": base.replace("-", " ").title(), "slug": slug, "createdAt": now, "updatedAt": now, "thumbnail": None,
        "camera": {"spawnPosition": {"x": round((min(xs) + max(xs)) / 2, 2), "y": 1.7, "z": round((min(zs) + max(zs)) / 2, 2)},
                   "spawnRotationY": 0, "fov": 72},
        "scene": {"background": "#0b1f38", "hemisphereLight": {"skyColor": "#ffffff", "groundColor": "#d8d0c0", "intensity": 1.6},
                  "ambientLight": {"color": "#ffffff", "intensity": 0.5}},
        "walls": walls,
        "rooms": [{"id": "openings", "module": "rooms/openings.js", "exportName": "buildOpenings", "order": 1}],
        "models": [], "settings": [
            {"id": "exposure", "label": "Exposure", "section": "Lighting", "type": "range", "min": 0.1, "max": 2, "step": 0.02,
             "default": 1.0, "value": 1.0, "binding": "renderer.toneMappingExposure"},
            {"id": "ambient", "label": "Ambient fill", "section": "Lighting", "type": "range", "min": 0, "max": 2, "step": 0.01,
             "default": 0.9, "value": 0.9, "binding": "ambientRef.intensity"}],
        "source": {"blueprint": os.path.basename(imgs[0]), "px_per_ft": round(ppf, 3), "scale_grade": m.get("src"),
                   "review": m.get("rv")},
    }
    json.dump(project, open(os.path.join(d, "project.json"), "w"), indent=2)
    json.dump(walls, open(os.path.join(d, "walls.json"), "w"), indent=2)
    import cv2
    cv2.imwrite(os.path.join(d, "floorplan.png"), cv2.imread(imgs[0]))
    open(os.path.join(d, "rooms", "openings.js"), "w").write(openings_module(m.get("o", []), ppm))
    rv = m.get("rv") or {}
    open(os.path.join(d, "CLAUDE.md"), "w").write(f"""# Project: {project['name']} (AR Homes blueprint)

This HOMEMAKER project was generated from an AR Homes marketing floor plan by blueprints/homemaker/to_homemaker.py.
See ../../CLAUDE.md for HOMEMAKER documentation.

## What is here
- floorplan.png: the AR Homes blueprint. Walls line up with it at {ppm:.2f} px per metre ({ppf:.2f} px per foot).
- {len(lines)} wall lines traced automatically from thick strokes; ceiling {CEIL} m (9 ft).
- rooms/openings.js: {len(m.get('o', []))} window/door openings found in wall gaps (headers, sills, glass).
- Scale grade: {GRADE.get(m.get('src'), m.get('src'))}.{f" Reviewer: {rv.get('n')} measured sides, {rv.get('spread')}% spread; added {rv.get('added')} walls, removed {rv.get('removed')}." if rv else ''}

## Known limits (fix these to get closer to 1:1)
- The sheet may show several levels side by side; they are all placed at ground level here.
- Glass walls, sliders and some thin walls are often missing; stairs, furniture and fixtures may be traced as walls.
- AR Homes states its plan dimensions are approximate. When correcting scale, measure a printed room size on
  floorplan.png and use the floor-plan tool's wall-length calibration.
- The blueprint is copyrighted by AR Homes; keep this project private.
""")
    return slug, len(lines), len(m.get("o", []))

if __name__ == "__main__":
    models_path, fp_dir, out_root, *only = sys.argv[1:]
    models = json.load(open(models_path))
    todo = only or sorted(models)
    done = 0
    for b in todo:
        r = export(b, models[b], fp_dir, out_root)
        if r: done += 1; print(*r) if len(todo) <= 20 else None
    print(f"exported {done} of {len(todo)} sheets to {out_root}")
